def main() -> int:
    if not SRC.is_file():
        print(f"Missing source index: {SRC}", file=sys.stderr)
        return 1

    kept: list[str] = []
    for raw in SRC.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line:
            continue
        name = decl_name(line)
        if name in DROP_EXACT:
            continue
        # Interval concretes are re-injected in generic-friendly form; drop originals to avoid dupes
        if name in {"AngleInterval", "LengthInterval", "NumberInterval", "IntegerInterval"}:
            continue
        kept.append(rewrite_implements(line))

    concepts = [ln for ln in kept if kind(ln) == "concept"] + INJECT_CONCEPTS
    types = [ln for ln in kept if kind(ln) == "type"] + INJECT_TYPES

    def sort_key(line: str) -> str:
        return decl_name(line) or line

    concepts = sorted(set(concepts), key=sort_key)
    types = sorted(set(types), key=sort_key)

    header = [
        "# DESIGN SKETCH - not the live index.",
        "# Generated by tools/propose-merged-types-index.py from stdlib/types-and-concepts.txt.",
        "# Intent: collapse 2D/3D twins and repeated families behind type parameters.",
        "# Geometry2D/Geometry3D markers, polar/planar specialisations, and domain-specific",
        "# sums are kept where a parameter would erase a real distinction.",
        "# Convenience spellings people still want in APIs:",
        "#   Bounds2D = Bounds<Point2D,Vector2D>, Direction3D = Direction<Vector3D>,",
        "#   Pose3D = Pose<Point3D,Quaternion>, Bitmap = ImageBuffer<Color8>, etc.",
        "#   Annulus = RadialShellPlanar; SphericalShell ~ RadialShellSolid;",
        "#   CylindricalShell still wants Axis+Height (not fully collapsed here).",
        "#",
    ]

    body = header + concepts + types
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(body) + "\n", encoding="utf-8", newline="\n")

    src_concepts = sum(1 for ln in SRC.read_text(encoding="utf-8").splitlines() if ln.startswith("concept "))
    src_types = sum(1 for ln in SRC.read_text(encoding="utf-8").splitlines() if ln.startswith("type "))
    print(f"Wrote {OUT}")
    print(f"  live:     {src_concepts} concepts, {src_types} types")
    print(f"  proposed: {len(concepts)} concepts, {len(types)} types")
    print(f"  delta:    {len(concepts) - src_concepts:+d} concepts, {len(types) - src_types:+d} types")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
