def decl_name(line: str) -> str | None:
    m = re.match(r"^(?:concept|type)\s+([A-Za-z_][A-Za-z0-9_]*)", line)
    return m.group(1) if m else None


def kind(line: str) -> str:
    return line.split()[0]


