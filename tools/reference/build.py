#!/usr/bin/env python3
"""Build source-derived Markdown reference pages and the React reader's data.

This is a lexical catalog, not a second Plato parser or semantic checker. Every
source byte is retained in ordered slices. Unsupported layouts fail explicitly.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import posixpath
import re
import subprocess
import time
from functools import lru_cache
from pathlib import Path
from urllib.parse import quote, unquote

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / 'docs/reference'
OUTPUT = ROOT / 'tools/reference-reader/public/reference.json'
TIERS = ('foundation', 'geometry', 'graphics', 'future')
GENERATED = '<!-- Generated by tools/reference/build.py; do not edit. -->'


def read(path: Path) -> str:
    return path.read_text(encoding='utf-8-sig').replace('\r\n', '\n')


def digest(text: str) -> str:
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def mask_source(source: str) -> str:
    """Mask comments and strings, preserving offsets and newlines."""
    pattern = r'//[^\n]*|/\*[\s\S]*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\''
    return re.sub(pattern, lambda m: re.sub(r'[^\n]', ' ', m[0]), source)


def depths(masked: str) -> list[int]:
    result, depth = [], 0
    for char in masked:
        result.append(depth)
        if char == '{':
            depth += 1
        elif char == '}':
            depth -= 1
        if depth < 0:
            raise ValueError('unbalanced source braces')
    if depth:
        raise ValueError('unbalanced source braces')
    return result


def slug(text: str) -> str:
    return re.sub(r'[^\w]+', '-', text.lower(), flags=re.UNICODE).strip('-')


def is_signature(masked: str, start: int, end: int) -> bool:
    """Require a balanced parameter list followed by a return annotation."""
    opening = masked.index('(', start, end)
    depth = 1
    position = opening + 1
    while position < end and depth:
        if masked[position] == '(':
            depth += 1
        elif masked[position] == ')':
            depth -= 1
        position += 1
    while position < end and masked[position].isspace():
        position += 1
    return depth == 0 and position < end and masked[position] == ':'


def slices(source: str) -> list[tuple[str, int, int, str]]:
    """Return a complete disjoint source partition and names for each slice.

    The first item includes a declaration's preceding commentary. A library is
    partitioned at member starts, preserving its opening/closing braces in the
    first/last slices. Every source character belongs to exactly one slice.
    """
    masked = mask_source(source)
    nesting = depths(masked)
    top = [(m, m.group(2), m.group(3)) for m in re.finditer(
        r'(?m)^\s*((?:unique\s+)?)(primitive|type|interface|concept|library)\s+(\w+)', masked)
        if nesting[m.start(2)] == 0]
    if not top:
        raise ValueError('no top-level declaration found')
    starts = []
    for index, (match, kind, name) in enumerate(top):
        end = top[index + 1][0].start() if index + 1 < len(top) else len(source)
        if kind != 'library':
            starts.append((match.start(), name, kind))
            continue
        # Method names begin a statement at library brace depth one. Parameter
        # contents may span lines; names inside a body have greater brace depth.
        members = [m for m in re.compile(r'(?m)^[ \t]*(\w+)[ \t]*\(').finditer(masked, match.end(), end)
                   if nesting[m.start(1)] == 1 and is_signature(masked, m.start(1), end)]
        if not members:
            starts.append((match.start(), name, kind))
        else:
            for member_index, member in enumerate(members):
                offset = match.start() if member_index == 0 else member.start()
                # Include the immediately preceding comment/blank lines with
                # their member. The partition remains lossless regardless.
                if member_index:
                    previous = offset
                    while previous > match.end():
                        line_end = previous - 1
                        line_start = source.rfind('\n', 0, line_end) + 1
                        line = source[line_start:line_end].strip()
                        if line and not line.startswith('//'):
                            break
                        offset = line_start
                        previous = line_start
                starts.append((offset, member.group(1), 'function'))
    starts[0] = (0, starts[0][1], starts[0][2])
    result = []
    for index, (start, name, kind) in enumerate(starts):
        end = starts[index + 1][0] if index + 1 < len(starts) else len(source)
        result.append((name, start, end, kind))
    if ''.join(source[start:end] for _, start, end, _ in result) != source:
        raise ValueError('source partition lost content')
    return result


def relative_link(from_path: Path, target: Path) -> str:
    return posixpath.relpath(target.relative_to(ROOT).as_posix(), from_path.parent.relative_to(ROOT).as_posix())


def generated_api() -> tuple[dict[Path, str], dict[str, str]]:
    outputs, inputs = {}, {}
    sources = [(tier, path) for tier in TIERS for path in sorted((ROOT / 'stdlib' / tier).glob('*.plato'))]
    sources += [('legacy', path) for path in sorted((ROOT / 'legacy/stdlib-legacy').glob('*.plato'))]
    if not sources or any(not any(t == tier for t, _ in sources) for tier in (*TIERS, 'legacy')):
        raise ValueError('a source tier is empty; refusing vacuous reference coverage')
    catalog = []
    for tier, source_path in sources:
        source = read(source_path)
        source_name = source_path.relative_to(ROOT).as_posix()
        inputs[source_name] = digest(source)
        stem = source_path.stem
        parent = DOCS / 'api' / tier / f'{stem}.md'
        kind_label = {'future': 'Aspirational vocabulary; not shipped by default.',
                      'legacy': 'Legacy vocabulary; compile separately from the forward library.'}.get(
                          tier, 'Forward shipping tier; presence here is not proof of executable coverage.')
        parts = slices(source)
        lines = [GENERATED, f'# {stem}', '', f'**Tier:** `{tier}`. {kind_label}', '',
                 f'**Source:** [{source_name}]({relative_link(parent, source_path)}).', '',
                 'Read each declaration or function below for its original comments, signature, and body.',
                 'The slices are ordered and lossless; the first and last library slices retain the block braces.',
                 'A signature without a body is an obligation, not an implemented algorithm.', '',
                 '## Declarations and functions', '']
        entries = []
        # Keep pages small without generating a filesystem entry for every tiny
        # accessor. Boundaries always fall BETWEEN complete source declarations.
        groups = []
        for part in parts:
            if groups and source.count('\n', groups[-1][0][1], part[2]) <= 160:
                groups[-1].append(part)
            else:
                groups.append([part])
        for number, group in enumerate(groups, 1):
            name, start, _, kind = group[0]
            end = group[-1][2]
            names = ', '.join(part[0] for part in group)
            child = parent.with_suffix('') / f'{number:03d}-{slug(name)}.md'
            line = source.count('\n', 0, start) + 1
            snippet = source[start:end]
            original_link = relative_link(child, source_path) + f'#L{line}'
            body = [GENERATED, f'# {stem}: {name}', '', f'**Tier:** `{tier}`.', '',
                    f'**Context:** [{stem}]({relative_link(child, parent)}).', '',
                    f'**Evidence:** [{source_name}, starting at line {line}]({original_link}).', '',
                    'This is source evidence, including authored comments and any preconditions or TODOs.',
                    'It is a lexical slice, not a standalone compilation unit. Names resolve in the complete tier union.',
                    'A comment states author intent; a body states an algorithm. Neither establishes that its laws hold.', '',
                    '## Members in this source section', '', names, '',
                    '## Declarations and implementations', '', '```plato', snippet.rstrip('\n'), '```', '',
                    '## Reading this entry', '',
                    'Parameters before the colon are input values; the type after the parameter list is the result.',
                    'The first parameter also supplies the dot-call receiver. Type parameters on a declaration are',
                    'bare names; free signature variables use `$`. Read the tier and domain guides for units, frames,',
                    'invariants, and the difference between a required interface member and a provided body.', '']
            outputs[child] = '\n'.join(body)
            lines.append(f'- [{names} — source section {number}]({relative_link(parent, child)})')
            for member_name, member_start, member_end, member_kind in group:
                entries.append({'name': member_name, 'kind': member_kind, 'start': member_start,
                                'end': member_end, 'line': source.count('\n', 0, member_start) + 1,
                                'page': child.relative_to(ROOT).as_posix()})
        outputs[parent] = '\n'.join(lines) + '\n'
        catalog.append({'source': source_name, 'sha256': digest(source), 'tier': tier,
                        'page': parent.relative_to(ROOT).as_posix(), 'entries': entries})
    manifest = DOCS / 'api/catalog.json'
    outputs[manifest] = json.dumps({'generator': 'tools/reference/build.py', 'sources': catalog}, indent=2) + '\n'
    for tier in (*TIERS, 'legacy'):
        target = DOCS / 'api' / tier / 'README.md'
        rows = [GENERATED, f'# {tier.capitalize()} API', '',
                'This source-derived catalog retains declarations, documentation comments, and implementations.',
                'Source presence is not an execution guarantee. Read the domain guides before using an algorithm.', '']
        for item in catalog:
            if item['tier'] == tier:
                path = ROOT / item['page']
                rows.append(f'- [{path.stem}]({relative_link(target, path)})')
        outputs[target] = '\n'.join(rows) + '\n'
    return outputs, inputs


def evidence_appendices() -> tuple[dict[Path, str], dict[str, str]]:
    outputs, inputs = {}, {}
    # Grammar and operator tables are exact evidence, not a portable grammar spec.
    for stem, files in {
        'grammar-source': ['parakeet/Parakeet.Grammars/PlatoGrammar.cs',
                           'parakeet/Parakeet.Grammars/PlatoTokenGrammar.cs',
                           'parakeet/Parakeet.Grammars/CommonGrammar.cs'],
        'operator-source': ['src/Plato.AST/Operators.cs'],
    }.items():
        page = DOCS / 'evidence' / f'{stem}.md'
        parts = [GENERATED, f'# {stem.replace("-", " ").title()}', '',
                 'Exact implementation evidence. The parser accepts more forms than the checked language;',
                 'a grammar production alone does not promise evaluation or C# emission.', '']
        for filename in files:
            path = ROOT / filename
            content = read(path)
            inputs[filename] = digest(content)
            parts += [f'## {path.name}', '', f'[Source]({relative_link(page, path)})', '',
                      '```csharp', content.rstrip(), '```', '']
        outputs[page] = '\n'.join(parts)
    # Open questions must be discoverable without trusting a manual status tally.
    page = DOCS / 'evidence/source-notes.md'
    parts = [GENERATED, '# Source TODOs and unresolved notes', '',
             'This is a lexical inventory of TODO, FIXME, HACK and not-implemented markers in the',
             'forward library, checker, interpreter and C# runtime. It may include historical comments;',
             'absence of a marker does not establish correctness. Tracker issues carry triage and lifecycle.', '']
    candidates = list((ROOT / 'stdlib').rglob('*.plato'))
    for directory in ('src/Plato.Compiler/Checking', 'src/Plato.Interpreter', 'src/Plato.Intrinsics'):
        candidates += [p for p in (ROOT / directory).rglob('*.cs') if not {'obj', 'bin', 'bonepile'} & set(p.parts)]
    for path in sorted(candidates):
        content = read(path)
        inputs[path.relative_to(ROOT).as_posix()] = digest(content)
        hits = [(n, line.strip()) for n, line in enumerate(content.splitlines(), 1)
                if re.search(r'\b(TODO|FIXME|HACK|NotImplementedException)\b', line)]
        if hits:
            name = path.relative_to(ROOT).as_posix()
            parts += [f'## {name}', '']
            for number, line in hits:
                safe = line.replace('`', "'").replace('[', '\\[').replace(']', '\\]')
                parts.append(f'- [Line {number}]({relative_link(page, path)}#L{number}): {safe}')
            parts.append('')
    outputs[page] = '\n'.join(parts)
    return outputs, inputs


def local_links(path: Path, markdown: str):
    # Exclude code fences; filenames and brackets in source are not doc links.
    # Preserve offsets because the bundle rewrites matches in the ORIGINAL text.
    text = re.sub(r'^```[^\n]*\n[\s\S]*?^```\s*$',
                  lambda m: re.sub(r'[^\n]', ' ', m[0]), markdown, flags=re.MULTILINE)
    for match in re.finditer(r'(?<!!)\[[^\]\n]+\]\(([^)\n]+)\)', text):
        target = match.group(1).strip().strip('<>')
        if re.match(r'^[a-zA-Z][\w+.-]*:', target) or target.startswith(('#', '/')):
            continue
        name, _, fragment = target.partition('#')
        resolved = resolve_target(path.parent, unquote(name))
        try:
            resolved.relative_to(ROOT)
        except ValueError as exc:
            raise ValueError(f'{path}: link escapes repository: {target}') from exc
        yield match, resolved, fragment


@lru_cache(maxsize=None)
def resolve_target(parent: Path, name: str) -> Path:
    return (parent / name).resolve()


def reader_bundle(pages: dict[Path, str]) -> dict:
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    result = []
    checked = set(pages)
    for path, markdown in sorted(pages.items(), key=lambda item: (item[0] != DOCS / 'README.md', item[0])):
        raw_markdown = markdown
        title = re.search(r'^# (.+)$', markdown, re.MULTILINE)
        if not title:
            raise ValueError(f'{path}: missing H1 title')
        links = list(local_links(path, markdown))
        for match, resolved, fragment in reversed(links):
            if resolved not in checked:
                if not resolved.exists():
                    raise ValueError(f'{path.relative_to(ROOT)}: missing link target {resolved.relative_to(ROOT)}')
                checked.add(resolved)
            if resolved in pages:
                href = '#/' + resolved.relative_to(ROOT).with_suffix('').as_posix()
                if fragment:
                    href += '@' + fragment
            else:
                # parakeet is a separate Git repository: pin to its gitlink,
                # not a nonexistent path inside the parent repository's blob.
                relative = resolved.relative_to(ROOT).as_posix()
                if relative.startswith('parakeet/'):
                    tree = subprocess.check_output(['git', 'ls-tree', 'HEAD', 'parakeet'], cwd=ROOT, text=True)
                    sha = tree.split()[2]
                    href = f'https://github.com/ara3d/parakeet/blob/{sha}/' + quote(relative[len('parakeet/'):])
                else:
                    href = f'https://github.com/cdiggins/plato/blob/{revision}/' + quote(relative)
                if fragment:
                    href += '#' + fragment
            old = match.group(0)
            new = old[:old.index('](') + 2] + href + ')'
            markdown = markdown[:match.start()] + new + markdown[match.end():]
        rel = path.relative_to(ROOT).as_posix()
        result.append({'id': rel[:-3], 'path': rel, 'title': title[1],
                       'group': list(path.relative_to(DOCS).parts[:-1]), 'markdown': markdown,
                       'rawMarkdown': raw_markdown})
    return {'schemaVersion': 1, 'sourceRevision': revision, 'pages': result}


def build(check: bool = False) -> dict:
    outputs, inputs = generated_api()
    extra, evidence_inputs = evidence_appendices()
    outputs.update(extra)
    inputs.update(evidence_inputs)
    outputs[DOCS / 'evidence/inputs.json'] = json.dumps({'sha256': dict(sorted(inputs.items()))}, indent=2) + '\n'
    expected = set(outputs)
    # Only the generator-owned trees may have obsolete output removed.
    actual = {p for folder in ('api', 'evidence') for p in (DOCS / folder).rglob('*') if p.is_file()}
    existing = {p: read(p) for p in outputs if p.exists()}
    stale = [p for p, text in outputs.items() if existing.get(p) != text]
    obsolete = actual - expected
    if check and (stale or obsolete):
        paths = [p.relative_to(ROOT).as_posix() for p in sorted(set(stale) | obsolete)]
        raise ValueError('stale generated reference; run python tools/reference/build.py:\n' + '\n'.join(paths[:30]))
    if not check:
        for path in obsolete:
            # Windows scanners and concurrent read-only reference audits may
            # briefly hold a file without delete sharing. Retry only that lock.
            for attempt in range(10):
                try:
                    path.unlink()
                    break
                except OSError as error:
                    if getattr(error, 'winerror', None) != 32 or attempt == 9:
                        raise
                    time.sleep(0.1)
        for path, text in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            if existing.get(path) != text:
                path.write_text(text, encoding='utf-8', newline='\n')
    pages = {p: text for p, text in outputs.items() if p.suffix == '.md'}
    pages.update({p: read(p) for p in DOCS.rglob('*.md') if p.name != 'PROGRESS.md' and p not in outputs})
    bundle = reader_bundle(pages)
    # Data is a build product, deliberately not tracked and not HEAD-ratcheted.
    # --check validates tracked freshness without touching the reader's output.
    if not check:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(json.dumps(bundle, ensure_ascii=False), encoding='utf-8')
    return {'pages': len(pages), 'sources': len(inputs), 'check': check}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check generated Markdown freshness and all local links')
    args = parser.parse_args()
    try:
        print(json.dumps(build(args.check)))
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        parser.exit(1, f'{error}\n')
