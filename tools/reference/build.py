def page_door(group: list[str]) -> str:
    """The site door a page belongs to (reader contract v2); the reference home is 'home'."""
    return DOORS.get(group[0], 'design') if group else 'home'


def page_status(group: list[str]) -> str | None:
    """Tier status for API pages and tier library guides; None for every other page."""
    if len(group) >= 2 and group[0] in ('api', 'library'):
        return TIER_STATUS.get(group[1])
    return None


def example_groups() -> dict:
    """Every fixture group with its inputs, source files and declared reference laws."""
    groups = {}
    for folder in sorted(p for p in EXAMPLES.iterdir() if p.is_dir() and p.name != 'prelude'):
        listed = folder / 'inputs.txt'
        inputs = ([line.strip() for line in read(listed).splitlines()
                   if line.strip() and not line.strip().startswith('#')]
                  if listed.exists() else [(EXAMPLES / 'prelude').relative_to(ROOT).as_posix()])
        files = [{'path': f.relative_to(ROOT).as_posix(), 'source': read(f)}
                 for f in sorted(folder.glob('*.plato'))]
        laws = sorted({m for f in files for m in re.findall(r'\b(Law_Reference\w*)\s*\(', f['source'])})
        groups[folder.name] = {'inputs': inputs, 'files': files, 'laws': laws}
    return groups


def split_bundle(bundle: dict, symbol_records: list[dict]) -> dict[str, object]:
    """Reader data v2: a small index, one file per page, a lazily loaded search text, examples.

    Keys are paths relative to the reader's public folder; values are JSON-serialisable.
    """
    declarations = {r['page']: [d['declaration'] for d in r.get('declarations', [])]
                    for r in symbol_records}
    symbols = {name: [dict(entry, declarations=declarations.get(entry['id'], []))
                      for entry in entries] for name, entries in bundle['symbols'].items()}
    index_pages, files, search = [], {}, []
    for page in bundle['pages']:
        index_pages.append({'id': page['id'], 'path': page['path'], 'title': page['title'],
                            'group': page['group'], 'door': page_door(page['group']),
                            'status': page_status(page['group'])})
        files[f"pages/{page['id']}.json"] = {'id': page['id'], 'markdown': page['markdown'],
                                             'rawMarkdown': page['rawMarkdown']}
        search.append({'id': page['id'], 'text': page['rawMarkdown']})
    files['reference-index.json'] = {'schemaVersion': 2, 'sourceRevision': bundle['sourceRevision'],
                                     'pages': index_pages, 'symbols': symbols,
                                     'aliases': bundle['aliases']}
    files['search.json'] = {'schemaVersion': 2, 'pages': search}
    files['examples.json'] = {'schemaVersion': 2, 'groups': example_groups()}
    return files


def reader_bundle(pages: dict[Path, str], aliases: dict[str, str] | None = None) -> dict:
    revision = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    result = []
    symbols: dict[str, list[dict[str, str]]] = {}
    checked = set(pages)
    for path, markdown in sorted(pages.items(), key=lambda item: (item[0] != DOCS / 'README.md', item[0])):
        raw_markdown = markdown
        title = re.search(r'^# (.+)$', markdown, re.MULTILINE)
        if not title:
            raise ValueError(f'{path}: missing H1 title')
        links = list(local_links(path, markdown))
        for match, resolved, fragment in reversed(links):
            if resolved not in checked:
                if not resolved.exists():
                    raise ValueError(f'{path.relative_to(ROOT)}: missing link target {resolved.relative_to(ROOT)}')
                checked.add(resolved)
            if resolved in pages:
                href = '#/' + resolved.relative_to(ROOT).with_suffix('').as_posix()
                if fragment:
                    href += '@' + fragment
            else:
                # parakeet is a separate Git repository: pin to its gitlink,
                # not a nonexistent path inside the parent repository's blob.
                relative = resolved.relative_to(ROOT).as_posix()
                if relative.startswith('parakeet/'):
                    tree = subprocess.check_output(['git', 'ls-tree', 'HEAD', 'parakeet'], cwd=ROOT, text=True)
                    sha = tree.split()[2]
                    href = f'https://github.com/ara3d/parakeet/blob/{sha}/' + quote(relative[len('parakeet/'):])
                else:
                    href = f'https://github.com/cdiggins/plato/blob/{revision}/' + quote(relative)
                if fragment:
                    href += '#' + fragment
            old = match.group(0)
            new = old[:old.index('](') + 2] + href + ')'
            markdown = markdown[:match.start()] + new + markdown[match.end():]
        rel = path.relative_to(ROOT).as_posix()
        page_id = rel[:-3]
        page = {'id': page_id, 'path': rel, 'title': title[1],
                'group': list(path.relative_to(DOCS).parts[:-1]), 'markdown': markdown,
                'rawMarkdown': raw_markdown}
        result.append(page)
        if '/api/' in page_id:
            for name in symbol_names_for_page(title[1], raw_markdown, page_id):
                symbols.setdefault(name, []).append({'id': page_id, 'title': title[1]})
    return {'schemaVersion': 1, 'sourceRevision': revision, 'pages': result, 'symbols': symbols,
            'aliases': aliases or {}}


def build(check: bool = False) -> dict:
    outputs, inputs = generated_api()
    extra, evidence_inputs = evidence_appendices()
    outputs.update(extra)
    inputs.update(evidence_inputs)
    outputs[DOCS / 'evidence/inputs.json'] = json.dumps({
        'normalization': 'UTF-8 without BOM; CRLF normalized to LF; SHA-256 of UTF-8 text',
        'sha256': dict(sorted(inputs.items()))}, indent=2) + '\n'
    aliases = load_aliases(outputs)
    if check:
        problems = fixture_violations(DOCS)
        if problems:
            raise ValueError('fixture check failed:\n' + '\n'.join(problems))
    expected = set(outputs) | {ALIASES}
    # Only the generator-owned trees may have obsolete output removed.
    actual = {p for folder in ('api', 'evidence') for p in (DOCS / folder).rglob('*') if p.is_file()}
    existing = {p: read(p) for p in outputs if p.exists()}
    stale = [p for p, text in outputs.items() if existing.get(p) != text]
    obsolete = actual - expected
    if check and (stale or obsolete):
        paths = [p.relative_to(ROOT).as_posix() for p in sorted(set(stale) | obsolete)]
        raise ValueError('stale generated reference; run python tools/reference/build.py:\n' + '\n'.join(paths[:30]))
    if not check:
        for path in obsolete:
            # Windows scanners and concurrent read-only reference audits may
            # briefly hold a file without delete sharing. Retry only that lock.
            for attempt in range(10):
                try:
                    path.unlink()
                    break
                except OSError as error:
                    if getattr(error, 'winerror', None) != 32 or attempt == 9:
                        raise
                    time.sleep(0.1)
        for path, text in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            if existing.get(path) != text:
                path.write_text(text, encoding='utf-8', newline='\n')
    pages = {p: text for p, text in outputs.items() if p.suffix == '.md'}
    pages.update({p: read(p) for p in DOCS.rglob('*.md') if p.name != 'PROGRESS.md' and p not in outputs})
    bundle = reader_bundle(pages, aliases)
    # Data is a build product, deliberately not tracked and not HEAD-ratcheted.
    # --check validates tracked freshness without touching the reader's output.
    if not check:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(json.dumps(bundle, ensure_ascii=False), encoding='utf-8')
        brand.write(OUTPUT.parent / 'brand')
        full, llms = text_exports(bundle)
        (PUBLIC / 'plato-reference.txt').write_text(full, encoding='utf-8', newline='\n')
        (PUBLIC / 'llms.txt').write_text(llms, encoding='utf-8', newline='\n')
        records = json.loads(outputs[DOCS / 'api/symbols.json'])['symbols']
        shutil.rmtree(PUBLIC / 'pages', ignore_errors=True)
        for name, value in split_bundle(bundle, records).items():
            target = PUBLIC / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(json.dumps(value, ensure_ascii=False), encoding='utf-8')
    return {'pages': len(pages), 'sources': len(inputs), 'check': check}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check generated Markdown freshness and all local links')
    args = parser.parse_args()
    try:
        print(json.dumps(build(args.check)))
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        parser.exit(1, f'{error}\n')
